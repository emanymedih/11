# что проверяется при индивидуальных испытаниях — по фактическому составу оборудования тома
def checks(bld, code):
    eq = ' '.join(f'{x[1]} {x[2]}' for x in EQ[(bld, code)])
    has = lambda *ws: any(w in eq for w in ws)
    c = []
    if code == 'СПС':
        c.append('формирование извещений «Пожар», «Неисправность» адресными пожарными извещателями (ручными и дымовыми) и их передача на приборы приёмно-контрольные и управления;')
        c.append('контроль исправности адресных линий связи (ДПЛС) и работа изолирующих блоков;')
        c.append('запуск СОУЭ: ' + ', '.join(x for x, ok in [('световые оповещатели «Выход»', has('ОСТ')), ('звуковые оповещатели', has('ОПЗ')),
                                                          ('речевые оповещатели и прибор речевого оповещения', has('Рупор', 'ОПР'))] if ok) + ';')
        c.append('выдача управляющих сигналов адресными релейными блоками' + (' и устройствами коммуникационными;' if has('УК-ВК') else ';'))
        if has('БКИ'): c.append('отображение состояния на блоке контроля и индикации;')
    elif code == 'СКУД':
        c.append('считывание идентификаторов считывателями и управление замками контроллерами доступа;')
        c.append('работа кнопок выхода' + (' и устройств аварийной разблокировки дверей;' if has('ST-ER115') else ';'))
        if has('видеодомофон'): c.append('работа видеодомофона (монитор и вызывные панели);')
        if has('ворот'): c.append('управление приводами ворот;')
        if has('противотаранн'): c.append('работа противотаранного устройства (пост остановки колёсного автотранспорта) от пульта управления;')
        if has('Рабочее место', 'рабочее место'): c.append('передача событий на рабочее место оператора;')
    elif code == 'СКС':
        c.append('наличие соединения (link) на портах коммутационного оборудования для всех линий рабочих мест;')
        if has('елефон'): c.append('работоспособность телефонных аппаратов;')
        c.append('соответствие маркировки розеток и портов коммутационного оборудования кабельному журналу;')
    elif code == 'СОТ':
        c.append('формирование и передача изображения всеми видеокамерами, питание камер по PoE;')
        c.append('работа коммутационного оборудования;')
        if has('бесперебойного'): c.append('работа источника бесперебойного питания;')
    elif code == 'СОТС':
        if has('звещатель'): c.append('формирование тревожных извещений охранными извещателями и постами кнопочными;' if has('ПКЕ') else 'формирование тревожных извещений охранными извещателями;')
        if has('КДЛ'): c.append('контроль исправности адресных линий связи и работа контроллера двухпроводной линии;')
        if has('ОПЗ', 'Маяк'): c.append('работа оповещателей' + (' и адресных релейных блоков;' if has('СП2') else ';'))
        if has('БКИ'): c.append('отображение состояния на блоке контроля и индикации;')
    if has('РИП', 'ШПС', 'Батарея'): c.append('работа от основного и резервного источников питания, автоматический переход на резерв и обратно;')
    c[-1] = c[-1].rstrip(';') + '.'
    return c


def cap(s): return s[:1].upper() + s[1:]

def d_(s): return dt.datetime.strptime(s, '%d.%m.%Y').date()
def ds(d): return d.strftime('%d.%m.%Y')
def dl(d): return f'«{d.day:02d}» {MONTHS[d.month]} {d.year} г.'


def dates(bld, code):
    prot = d_(C.DATES[bld]['prot']); start = prot + dt.timedelta(days=SHIFT[bld][code])
    end = start + dt.timedelta(days=3)
    return dict(mount=d_(C.DATES[bld]['act']), prot=prot, start=start, end=end, enter=end + dt.timedelta(days=1))


def new_doc():
    doc = Document()
    s = doc.sections[0]; s.page_width, s.page_height = Mm(210), Mm(297)
    s.left_margin = Mm(25); s.right_margin = Mm(10); s.top_margin = Mm(15); s.bottom_margin = Mm(15)
    st = doc.styles['Normal']; st.font.name = 'Times New Roman'; st.font.size = Pt(10)
    return doc


def head(doc, title, sub, code, bld, no, date):
    lab(doc, 'Объект капитального строительства:', C.OBJ)
    lab(doc, 'Застройщик (технический заказчик):', C.ZAK)
    lab(doc, 'Лицо, осуществляющее строительство:', C.STR)
    lab(doc, 'Лицо, выполнившее монтаж и пусконаладочные работы:', C.ISP)
    para(doc, 'АКТ', 14, True, align=A.CENTER, before=8, after=0)
    para(doc, title, 12, True, align=A.CENTER, after=0)
    para(doc, f'{C.SYSN[code]}, здание {bld}' + (f'. {sub}' if sub else ''), 12, True, align=A.CENTER, after=6)
    t = doc.add_table(rows=1, cols=2); t.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell(t.rows[0].cells[0], f'№ {no}', 11); cell(t.rows[0].cells[1], dl(date), 11, align=A.RIGHT)


def commission(doc, reps, verb):
    para(doc, 'Комиссия в составе:', 10, True, before=4)
    for role, who, _ in reps: lab(doc, role + ':', who, 10)
    para(doc, verb, 10, before=3)


def items(doc, xs):
    for k, x in enumerate(xs, 1):
        p = para(doc, after=1); font(p.add_run(f'{k}. '), 10, True); font(p.add_run(x), 10, False, True)


def labeled(doc, label, text):
    p = para(doc, before=4); font(p.add_run(label + ' '), 10, True); font(p.add_run(text), 10, False, True)


def signs(doc, reps):
    para(doc, 'Подписи:', 10, True, before=6, after=2)
    sg = doc.add_table(rows=0, cols=2)
    for role, _, who in reps:
        rc = sg.add_row().cells
        cell(rc[0], role, 9, True); cell(rc[1], f'____________________ / {who} /', 10, align=A.RIGHT)
    fix_widths(sg, [Mm(110), Mm(65)])


def eq_table(doc, bld, code):
    H = ['№', 'Наименование оборудования', 'Тип, марка', 'Поз. обозн. по ИД', 'Кол-во, шт.']
    W = [Mm(8), Mm(82), Mm(48), Mm(22), Mm(15)]
    t = doc.add_table(rows=1, cols=len(H)); borders(t); t.autofit = False
    for k, h in enumerate(H): cell(t.rows[0].cells[k], h, 8, True, A.CENTER)
    total = 0
    for n, (pos, nm, typ, mf, qty, src) in enumerate(EQ[(bld, code)], 1):
        rr = t.add_row().cells; total += qty
        for k, x in enumerate([n, nm, typ, pos, qty]):
            cell(rr[k], x, 8, align=A.CENTER if k in (0, 3, 4) else A.LEFT)
    rr = t.add_row().cells; cell(rr[1], 'Итого единиц оборудования', 8, True); cell(rr[4], total, 8, True, A.CENTER)
    fix_widths(t, W)
    return total


def ctx(bld, code):
    v = C.vol(bld, code); d = dates(bld, code)
    n = dict(o=f'{code}-{bld}-О', m=f'{code}-{bld}-М', i=f'{code}-{bld}-И', p=f'{code}-{bld}-П', v=f'{code}-{bld}-В',
             t=f'ТО-{code}-{bld}', prot=f'ПИ-{code}-{bld}')
    return v, d, n


def save(doc, name):
    os.makedirs(OUT, exist_ok=True); p = f'{OUT}/{name}.docx'; doc.save(p); return p


