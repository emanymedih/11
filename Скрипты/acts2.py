import acts, r
DOC = {'TRG': 'сертификат соответствия', 'KPS': 'сертификат соответствия', 'GOFRA': 'сертификат соответствия',
       'SKOBA': 'паспорт', 'PENA': 'сертификат соответствия', 'GERM': 'сертификат соответствия'}
UNIT = {'баллон': ('баллон', 'баллона', 'баллонов'), 'картридж': ('картридж', 'картриджа', 'картриджей')}
def plural(n, forms):
    n = abs(n) % 100; n1 = n % 10
    if 10 < n < 20: return forms[2]
    if n1 == 1: return forms[0]
    if 1 < n1 < 5: return forms[1]
    return forms[2]

def p3_for(code, no):
    pos = 0; lines = []
    for title, items in r.VOL[code][3]:
        mine = title.startswith(f'АОСР № {no} ')
        for key, qty in items:
            pos += 1
            if not mine: continue
            nm, mf, un, dk = r.M[key]
            unit = plural(qty, UNIT[un]) if un in UNIT else un
            doc = DOC.get(key, 'документ о качестве')
            lines.append(f'{nm}, {mf} — {qty} {unit} ({doc} — реестр, поз. {pos});')
    lines[-1] = lines[-1][:-1] + '.'
    lines.append(f'Реквизиты документов (сертификатов, паспортов, писем) — в Реестре документов о качестве (том {code}, '
                 'здание КПП), являющемся неотъемлемой частью настоящего акта (приложение 1).')
    return lines

