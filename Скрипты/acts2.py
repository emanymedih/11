def plural(n, forms):
    n = abs(n) % 100; n1 = n % 10
    if 10 < n < 20: return forms[2]
    if n1 == 1: return forms[0]
    if 1 < n1 < 5: return forms[1]
    return forms[2]

def _rekv(d):
    """Реквизиты документа: вид, номер, дата (строго по п. 3 формы)."""
    kind = DOC.get(d, 'документ о качестве'); D = r.D[d]; num, dt = D[1], D[2]
    if num in ('—', None, ''):
        return kind + (' изготовителя' if kind == 'паспорт' else '')
    num = num if (num.startswith('№') or num.startswith('исх')) else '№ ' + num
    return f'{kind} {num}' + (f' от {dt}' if dt not in ('—', None, '') else '')

def p3_items(groups, match, code, bld):
    """п. 3: наименование материала (изделия) и реквизиты документов о качестве (с позицией в реестре)."""
    pos = 0; lines = []
    for title, items in groups:
        mine = match(title)
        for key, qty in items:
            nm, mf, un, dks = r.M[key]
            dks = dks if isinstance(dks, list) else [dks]
            ps = list(range(pos + 1, pos + 1 + len(dks))); pos += len(dks)
            if not mine: continue
            docs = '; '.join(f'{_rekv(d)} (реестр, поз. {p})' for d, p in zip(dks, ps))
            lines.append(f'{nm} — {docs};')
    lines[-1] = lines[-1][:-1] + '.'
    return lines

def p3_for(code, no):
    return p3_items(r.VOL[code][3], lambda t: t.startswith(f'АОСР № {no} '), code, 'КПП')

