def reg(s):
    return (f'Реквизиты документов о качестве — по Реестру документов о качестве (том {s}, здание КПП), '
            'являющемуся неотъемлемой частью настоящего акта (приложение 1).')

def p2(s):
    rd, l, _ = SYS[s]
    return [f'Рабочая документация {rd},', f'лист {l}. {DEV}']

def apps(s, kj=False):
    _, _, il = SYS[s]
    a = [f'Реестр документов о качестве (том {s}, здание КПП) с копиями документов.',
         f'Исполнительная схема {ID}, лист {il}.']
    if kj: a.append(f'Кабельный журнал {KJ} (раздел {s}).')
    return a

def norms_fire(s, first):
    rd, l, _ = SYS[s]
    return [first, 'ГОСТ Р 59638-2021; ГОСТ Р 59639-2021; СП 76.13330.2016;', f'рабочая документация {rd}, лист {l}.']

def norms(s, first):
    rd, l, _ = SYS[s]
    return [first, f'рабочая документация {rd}, лист {l}.']

def sleeves(s, n, start, end, slab=None, wall=None, trg=2, pena=1, germ=2, cable_act=None, fire=False):
    _, _, il = SYS[s]
    where = []
    if slab: where.append(f'в перекрытии толщиной 150 мм на отм. +3,000 — {slab} шт.')
    if wall: where.append(f'{"в стене" if wall[0]==1 else "в стенах"} толщиной 150 мм на отм. {wall[1]} — {wall[0]} шт.')
    total = (slab or 0) + (wall[0] if wall else 0)
    p1 = ['Монтаж защитных гильз и герметизация',
          f'кабельных проходок {s} здания КПП {AX}: ' + '; '.join(where) + (f' Всего — {total} шт.' if len(where)>1 else '') + ' Гильзы из жёсткой ПВХ-трубы d20 мм.']
    kinds = ', '.join(k for k, v in (('перекрытие', slab), ('стена', wall)) if v)
    dop = []
    if slab: dop.append('Перекрытие в местах прохода не имеет нормируемого предела огнестойкости.')
    dop.append(f'Узлы — по экспликациям кабельных проходок на листе {il} ИД. Гильзы установлены до прокладки кабелей; '
               f'герметизация внутри гильз выполнена после прокладки кабельных линий (акт № {cable_act}).')
    first = 'ПУЭ (7-е изд.), п. 2.1.58; СП 6.13130.2025;' if fire else 'ПУЭ (7-е изд.), п. 2.1.58; СП 76.13330.2016;'
    return dict(
        no=f'1-{s}-КПП', file=f'АОСР 1-{s}-КПП', date=end, start=start, end=end,
        p1=p1, p2=p2(s),
        p3=[f'{TRG} — {trg} м;', f'{PENA} — {pena} {"баллон" if pena==1 else "баллона"};', f'{GERM} — {germ} картриджа.', reg(s)],
        p4=[f'Исполнительная схема {ID}, лист {il}', f'(экспликации кабельных проходок: {kinds}).'],
        p6=(['ПУЭ (7-е изд.), п. 2.1.58; СП 6.13130.2025;', 'ГОСТ Р 59638-2021; ГОСТ Р 59639-2021;',
             f'рабочая документация {SYS[s][0]}, лист {SYS[s][1]}.'] if fire else norms(s, first)),
        p7=['Отделочные работы в местах кабельных проходок.'],
        dop=[' '.join(dop)],
        apps=apps(s),
    )

